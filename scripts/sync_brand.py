"""Write studio/src/lib/brand.ts from brand/brand.json so every video uses YOUR channel name and colours.

Usage: python sync_brand.py            (run after brand.json is created or changed)
Missing fields fall back to neutral defaults.
"""
import json, os

ROOT = r"D:\DepthPOV"
SRC = os.path.join(ROOT, "brand", "brand.json")
OUT = os.path.join(ROOT, "studio", "src", "lib", "brand.ts")

DEFAULTS = {
    "channel_name": "Your Channel",
    "accent": {"threat": "#F2C230", "safe": "#3DDC84", "danger": "#E25544"},
    "character_colors": {
        "suit": "#2B3136",
        "suit2": "#3A434A",
        "stripe": "#2F9A92",
        "fins": "#FF8A1F",
        "fins_dark": "#D06A10",
        "lamp": "#FFF4C2",
    },
}


def main():
    b = json.load(open(SRC, encoding="utf-8-sig")) if os.path.exists(SRC) else {}
    acc = {**DEFAULTS["accent"], **{k: v for k, v in (b.get("accent") or {}).items() if k in DEFAULTS["accent"]}}
    cc = {**DEFAULTS["character_colors"], **(b.get("character_colors") or {})}
    brand = {"channel_name": b.get("channel_name", DEFAULTS["channel_name"]), "accent": acc, "character_colors": cc}
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/sync_brand.py from brand/brand.json - do not edit by hand.\n")
        f.write("export const BRAND = " + json.dumps(brand, indent=2, ensure_ascii=False) + " as const;\n")
    print("brand.ts written for", brand["channel_name"])


if __name__ == "__main__":
    main()
